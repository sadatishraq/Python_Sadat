#Escape Sequences
# \n - New Line
# \" - Double Quote
# \' - Single Quote
# \t - Tab
# \\ - To include a real backslash in the text '\'
# \b - Backspace

#\" - Double Quote
print("Hello \"Sadat\" ")
print('Hello "Sadat" ')

# \' - Single Quote
print("Hello \'Rose\'")
print("Hello 'Sadat' ")

# \n - New Line
print("Hello \nSadat")

# \t - Tab --> Gap between the words
print("Hello \tLabib")


# \\ - To include a real backslash in the text '\'
print("Path: C:\\User\\Sadat")

# \n
print("Message1\n")
print("Message2")
print("-----------------------------")
print("Message1")
print()
print("Message2")



