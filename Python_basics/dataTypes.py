# primitive data types in python
# 1. int
age = 24
print(type(age))

# 2. float
pi = 3.14159
print(type(pi))

# 3. string
name = "Sadat"
print(type(name))

# 4. boolean
is_a_student = True
print(type(is_a_student))

is_a_teacher = False
print(type(is_a_teacher))

# 5. complex
complex_number = 2 + 3j
print(type(complex_number))


numStr = "123"
int(numStr) # convert string to integer
print(type(int(numStr)))

n = None
print(type(n)) # NoneType

n = 20
print(type(n)) #NoneType --> int

